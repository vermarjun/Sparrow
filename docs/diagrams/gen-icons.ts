#!/usr/bin/env bun
// Regenerates src/icons.js from the Lucide icon nodes in web/node_modules (ISC, see LICENSE-lucide.txt).
//   bun docs/diagrams/gen-icons.ts
// Add a name to LUCIDE to make it available as <i class="ic" data-i="name">. Custom marks live in CUSTOM.
import { join } from 'node:path'

const LUCIDE = [
  'terminal', 'ship-wheel', 'anchor', 'database', 'globe', 'copy', 'scroll-text', 'messages-square', 'shield-check', 'server',
  'git-branch', 'check', 'file-text', 'users', 'inbox', 'eye', 'eye-off', 'zap', 'brain', 'hammer', 'compass', 'life-buoy',
  'package', 'plug', 'monitor', 'arrow-right', 'mail', 'settings', 'flag', 'layers', 'workflow', 'square-kanban', 'wrench', 'gauge',
  'timer', 'user', 'search', 'lock', 'x', 'circle-check', 'arrow-left-right', 'unplug', 'key-round', 'square-terminal', 'clipboard-list',
  'book-open', 'microscope', 'file-search', 'cpu', 'sparkles', 'feather', 'message-square', 'folder-git', 'folder', 'link', 'ban', 'clock', 'archive', 'git-merge', 'circle-x', 'list-checks', 'rocket', 'circle-alert', 'bug', 'split', 'hourglass',
]
const CUSTOM: Record<string, string> = {
  // The Sparrow mark: a small bird, head right, filled body with a notched tail.
  sparrow: '<path d="M21.2 7.6l-2.6.2C17.9 5.8 16 4.6 13.9 5 11.4 5.5 9.8 7.7 10 10.1 8.7 13 6.1 15.9 2.6 17.7c2.8.3 5.1.1 7-.6.9.5 2 .8 3.100.6 4-.5 6.5-4.2 5.7-8.3L21.2 7.6z" fill="currentColor" stroke="none"/><circle cx="15.8" cy="8.3" r=".9" style="fill:var(--eye)" stroke="none"/>',
}

const nodeToSvg = (nodes: [string, Record<string, string>][]) =>
  nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('')

const out: Record<string, string> = { ...CUSTOM }
for (const name of LUCIDE) {
  const mod = await import(join(import.meta.dir, `../../web/node_modules/lucide-react/dist/esm/icons/${name}.mjs`))
  if (!mod.__iconData) throw new Error(`lucide icon "${name}" has no __iconData (alias?)`)
  out[name] = nodeToSvg(mod.__iconData.node)
}
const body = `// Generated by gen-icons.ts. Lucide icons: ISC license (LICENSE-lucide.txt).\nwindow.ICONS = ${JSON.stringify(out, null, 1)}\n`
await Bun.write(join(import.meta.dir, 'src/icons.js'), body)
console.log(`icons.js: ${Object.keys(out).length} icons`)
