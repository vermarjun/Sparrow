#!/usr/bin/env bun
// Build the standalone Sparrow binary:
//   bun scripts/build-binary.ts [--target bun-darwin-arm64|bun-darwin-x64|bun-linux-x64|bun-linux-arm64|all] [--outdir dist/bin]
// Writes <outdir>/sparrow-<os>-<arch> (os: darwin|linux, arch: arm64|x64) — a name CONTRACT with the npm / install.sh /
// brew / release tooling. Default target: this machine. Builds web/dist when missing, embeds assets/** and web/dist/**
// through a generated entry (dist/build/entry.ts) that registers them in globalThis.__SPARROW_EMBED__ before the CLI loads;
// at run time they are materialised once to $SPARROW_HOME/app/<version>/ (src/shared/app.ts).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const ROOT = resolve(import.meta.dir, '..');
export const TARGETS = ['bun-darwin-arm64', 'bun-darwin-x64', 'bun-linux-x64', 'bun-linux-arm64'] as const;
export type Target = (typeof TARGETS)[number];

/** dist/bin file name for a bun target: bun-darwin-arm64 -> sparrow-darwin-arm64. */
export const outName = (t: Target) => `sparrow-${t.slice('bun-'.length)}`;

export function hostTarget(): Target {
  const os = process.platform === 'darwin' ? 'darwin' : process.platform === 'linux' ? 'linux' : null;
  const arch = process.arch === 'arm64' ? 'arm64' : process.arch === 'x64' ? 'x64' : null;
  if (!os || !arch) throw new Error(`unsupported host ${process.platform}-${process.arch}`);
  return `bun-${os}-${arch}` as Target;
}

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    return e.isDirectory() ? walk(p) : e.isFile() && e.name !== '.DS_Store' ? [p] : [];
  }).sort();
}

export interface Manifest { files: [rel: string, abs: string][]; build: string }

/** Every file of assets/** -> 'assets/…' and web/dist/** -> 'web/…', plus a build id (hash of paths + contents). */
export function collect(root = ROOT): Manifest {
  const files: [string, string][] = [];
  for (const f of walk(join(root, 'assets'))) files.push([`assets/${relative(join(root, 'assets'), f)}`, f]);
  for (const f of walk(join(root, 'web', 'dist'))) files.push([`web/${relative(join(root, 'web', 'dist'), f)}`, f]);
  const h = createHash('sha256');
  for (const [rel, abs] of files) h.update(rel).update('\0').update(readFileSync(abs)).update('\0');
  return { files, build: h.digest('hex').slice(0, 16) };
}

/** Source of the generated entry: embed every file, register the manifest, then hand over to the CLI. */
export function entrySource(m: Manifest, version: string, entryDir: string): string {
  const imp = m.files.map(([, abs], i) => `import f${i} from ${JSON.stringify(relative(entryDir, abs))} with { type: 'file' };`);
  const map = m.files.map(([rel], i) => `  ${JSON.stringify(rel)}: f${i},`);
  return [
    '// GENERATED by scripts/build-binary.ts — do not edit.',
    ...imp,
    `(globalThis as any).__SPARROW_EMBED__ = { version: ${JSON.stringify(version)}, build: ${JSON.stringify(m.build)}, files: {`,
    ...map,
    '} };',
    `const { entry } = await import(${JSON.stringify(relative(entryDir, join(ROOT, 'src', 'cli', 'entry')))});`,
    'process.exit(await entry(process.argv.slice(2)));',
    '',
  ].join('\n');
}

async function sh(cmd: string[], cwd = ROOT): Promise<void> {
  const p = Bun.spawn(cmd, { cwd, stdout: 'inherit', stderr: 'inherit', stdin: 'ignore' });
  const code = await p.exited;
  if (code !== 0) throw new Error(`${cmd.join(' ')} failed (exit ${code})`);
}

function ensureWeb() {
  if (existsSync(join(ROOT, 'web', 'dist', 'index.html'))) return Promise.resolve();
  console.log('web/dist missing: building the UI');
  return sh([process.execPath, 'install'], join(ROOT, 'web')).then(() => sh([process.execPath, 'run', 'build'], join(ROOT, 'web')));
}

/** `bun build --compile` output on macOS fails codesign verification as built; ad-hoc re-sign it. */
async function codesign(file: string, target: Target) {
  if (!target.startsWith('bun-darwin')) return;
  if (process.platform !== 'darwin') { console.warn(`warning: ${file} is a macOS binary built on ${process.platform}; not ad-hoc signed (arm64 macOS needs a signature: sign it on a Mac)`); return; }
  await sh(['codesign', '--force', '--sign', '-', file]);
  await sh(['codesign', '-v', file]);
}

export async function build(targets: Target[], outdir: string): Promise<string[]> {
  const version: string = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;
  await ensureWeb();
  const m = collect();
  const entryDir = join(ROOT, 'dist', 'build');
  mkdirSync(entryDir, { recursive: true });
  const entry = join(entryDir, 'entry.ts');
  writeFileSync(entry, entrySource(m, version, entryDir));
  mkdirSync(outdir, { recursive: true });
  const out: string[] = [];
  for (const t of targets) {
    const file = join(outdir, outName(t));
    console.log(`\n== ${t} -> ${relative(ROOT, file)} (v${version}, ${m.files.length} embedded files, build ${m.build})`);
    rmSync(file, { force: true });
    await sh([process.execPath, 'build', '--compile', `--target=${t}`, '--outfile', file, entry]);
    await codesign(file, t);
    out.push(file);
    console.log(`   ${(statSync(file).size / 1048576).toFixed(1)} MB`);
  }
  return out;
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { target: { type: 'string' }, outdir: { type: 'string', default: 'dist/bin' } } });
  const t = (values.target as string | undefined) ?? hostTarget();
  const targets: Target[] = t === 'all' ? [...TARGETS] : [t as Target];
  for (const x of targets) if (!TARGETS.includes(x)) { console.error(`unknown --target ${x}; one of ${TARGETS.join(', ')}, all`); process.exit(2); }
  const files = await build(targets, resolve(ROOT, values.outdir as string));
  console.log(`\nbuilt:\n${files.map((f) => '  ' + relative(ROOT, f)).join('\n')}`);
}
