import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const { version } = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
const binDir = resolve(root, process.env.SPARROW_BIN_DIR || "dist/bin");
const checksums = await readFile(resolve(root, "dist/checksums.txt"), "utf8");
function digest(name: string): string {
  const line = checksums.split("\n").find(line => line.endsWith(`  ${name}`));
  const hash = line?.split(/\s+/)[0];
  if (!hash || !/^[a-f0-9]{64}$/.test(hash)) throw new Error(`Missing checksum for ${name}`);
  return hash;
}
let formula = `# Generated by scripts/brew-formula.ts; copy to vermarjun/homebrew-tap.\nclass Sparrow < Formula\n  desc "Run coding agents in tmux with a local control plane"\n  homepage "https://github.com/vermarjun/Sparrow"\n  version "${version}"\n  license "MIT"\n\n  depends_on "tmux"\n`;
for (const os of ["darwin", "linux"]) {
  formula += `\n  on_${os === "darwin" ? "macos" : "linux"} do\n`;
  for (const arch of ["arm64", "x64"]) {
    const name = `sparrow-${os}-${arch}`;
    const hash = digest(name);
    const actual = createHash("sha256").update(await readFile(resolve(binDir, name))).digest("hex");
    if (actual !== hash) throw new Error(`Checksum mismatch for ${name}`);
    formula += `    on_${arch === "arm64" ? "arm" : "intel"} do\n      url "https://github.com/vermarjun/Sparrow/releases/download/v${version}/${name}", using: :nounzip\n      sha256 "${hash}"\n    end\n`;
  }
  formula += "  end\n";
}
formula += `\n  def install\n    binary = "sparrow-#{OS.mac? ? "darwin" : "linux"}-#{Hardware::CPU.arm? ? "arm64" : "x64"}"\n    bin.install binary => "sparrow"\n  end\n\n  test do\n    assert_match "sparrow #{version}", shell_output("#{bin}/sparrow --version")\n  end\nend\n`;
const dir = resolve(root, "dist/brew/Formula");
await mkdir(dir, { recursive: true });
await writeFile(resolve(dir, "sparrow.rb"), formula);
